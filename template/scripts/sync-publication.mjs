#!/usr/bin/env node
// Projects all generated translations into only the locale routes currently
// released. Factory runs this before Workers Static Assets builds, so a
// scheduled Git commit changing publication-plan.json is sufficient to publish
// the next wave.

import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const inputPath = path.join(root, "intake", "publication-plan.json");
const outputPath = path.join(root, "src", "config", "publication.ts");
const supported = ["en", "es", "de", "fr", "ja"];

if (!fs.existsSync(inputPath)) {
  throw new Error("缺少 intake/publication-plan.json");
}
const plan = JSON.parse(fs.readFileSync(inputPath, "utf-8"));
const published = plan.publishedLocales;
const policy = plan.releasePolicy || {};

if (plan.schemaVersion !== 1) throw new Error("publication-plan schemaVersion 必须是 1");
const generated = plan.generatedLocales;
if (
  !Array.isArray(generated)
  || generated.length < 1
  || generated[0] !== "en"
  || new Set(generated).size !== generated.length
  || generated.some((locale) => !supported.includes(locale))
) {
  throw new Error(`publication-plan.generatedLocales 必须是以 en 开头的支持语言子集：${supported.join(", ")}`);
}
if (!Array.isArray(published) || published.length < 1 || published.length > generated.length) {
  throw new Error("publication-plan.publishedLocales 数量不合法");
}
if (JSON.stringify(published) !== JSON.stringify(generated.slice(0, published.length))) {
  throw new Error(`publication-plan.publishedLocales 必须按 ${generated.join(" → ")} 顺序逐步增加`);
}
const expectedMode = generated.length === 1 ? "english-only" : "sequential";
const expectedIntervalDays = generated.length === 1 ? 0 : 3;
if (
  policy.mode !== expectedMode
  || JSON.stringify(policy.localeOrder) !== JSON.stringify(generated)
  || policy.intervalDays !== expectedIntervalDays
  || policy.timezone !== "Asia/Shanghai"
) {
  throw new Error("publication-plan.releasePolicy 不符合当前语言发布契约");
}

const source = `// Generated by scripts/sync-publication.mjs from intake/publication-plan.json.
// Do not edit this file by hand.
export const GENERATED_LOCALES = ${JSON.stringify(generated)} as const;
export type GeneratedLocale = (typeof GENERATED_LOCALES)[number];

export const PUBLISHED_LOCALES = ${JSON.stringify(published)} as const satisfies readonly GeneratedLocale[];
export type PublishedLocale = (typeof PUBLISHED_LOCALES)[number];
`;
fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, source, "utf-8");
console.log(`✓ 当前公开语言：${published.join(", ")}`);
