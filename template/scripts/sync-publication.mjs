#!/usr/bin/env node
// Projects all generated translations into only the locale routes currently
// released. Cloudflare Pages runs this in prebuild, so a scheduled Git commit
// changing publication-plan.json is sufficient to publish the next wave.

import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const inputPath = path.join(root, "intake", "publication-plan.json");
const outputPath = path.join(root, "src", "config", "publication.ts");
const expected = ["en", "es", "de", "fr", "ja"];

if (!fs.existsSync(inputPath)) {
  throw new Error("缺少 intake/publication-plan.json");
}
const plan = JSON.parse(fs.readFileSync(inputPath, "utf-8"));
const published = plan.publishedLocales;
const policy = plan.releasePolicy || {};

if (plan.schemaVersion !== 1) throw new Error("publication-plan schemaVersion 必须是 1");
if (JSON.stringify(plan.generatedLocales) !== JSON.stringify(expected)) {
  throw new Error(`publication-plan.generatedLocales 必须是 ${expected.join(", ")}`);
}
if (!Array.isArray(published) || published.length < 1 || published.length > expected.length) {
  throw new Error("publication-plan.publishedLocales 数量不合法");
}
if (JSON.stringify(published) !== JSON.stringify(expected.slice(0, published.length))) {
  throw new Error("publication-plan.publishedLocales 必须按 en → es → de → fr → ja 顺序逐步增加");
}
if (
  policy.mode !== "sequential"
  || JSON.stringify(policy.localeOrder) !== JSON.stringify(expected)
  || policy.intervalDays !== 3
  || policy.timezone !== "Asia/Shanghai"
) {
  throw new Error("publication-plan.releasePolicy 不符合 v1_0728 契约");
}

const source = `// Generated by scripts/sync-publication.mjs from intake/publication-plan.json.
// Do not edit this file by hand.
export const GENERATED_LOCALES = ${JSON.stringify(expected)} as const;
export type GeneratedLocale = (typeof GENERATED_LOCALES)[number];

export const PUBLISHED_LOCALES = ${JSON.stringify(published)} as const satisfies readonly GeneratedLocale[];
export type PublishedLocale = (typeof PUBLISHED_LOCALES)[number];
`;
fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, source, "utf-8");
console.log(`✓ 当前公开语言：${published.join(", ")}`);
